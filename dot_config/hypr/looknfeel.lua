-- hyprexpo workaround: an opaque fullscreen window (e.g. foot) becomes Hyprland's
-- "solitary" client, which bypasses renderWorkspace, so the overview is never drawn.
-- A near-1.0 fullscreen opacity blocks the solitary path (visually identical).
hl.config({
  decoration = {
    fullscreen_opacity = 0.999,
  },
})

-- Launchpad (logos.launchpad shell plugin) draws its own progressive blurred
-- background, so the compositor neither blurs nor animates its layer.
hl.layer_rule({ match = { namespace = "^omarchy-launchpad$" }, blur = false, no_anim = true })
